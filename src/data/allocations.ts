function normalizeRawRows(): MPLADSAllocation[] {
  return rawRows.map((row) => ({
    id: `MPLADS-ALLOC-${String(row.sn).padStart(4, '0')}`,
    serialNumber: row.sn,
    state: row.state,
    mpName: row.mp,
    constituency: row.constituency,
    allocatedAmount: row.amount,
    sourceName: ALLOCATION_SOURCE_NAME,
    sourceUrl: ALLOCATION_SOURCE_URL,
    sourceRetrievedAt: '2026-09-02T00:00:00Z',
    sourceRow: `Row ${row.sn}`,
    dataQualityFlags: detectQualityFlags(row),
  }));
}

export const localAllocations: MPLADSAllocation[] = normalizeRawRows();

export function getStatesWithAllocations(): string[] {
  const states = new Set(localAllocations.map((a) => a.state));
  return Array.from(states).sort((a, b) => a.localeCompare(b));
}

export function getStateAllocationSummary(): { state: string; totalAmount: number; mpCount: number; avgAmount: number }[] {
  const stateMap = new Map<string, { total: number; count: number }>();
  for (const alloc of localAllocations) {
    const existing = stateMap.get(alloc.state) || { total: 0, count: 0 };
    existing.total += alloc.allocatedAmount;
    existing.count += 1;
    stateMap.set(alloc.state, existing);
  }
  return Array.from(stateMap.entries())
    .map(([state, { total, count }]) => ({
      state,
      totalAmount: total,
      mpCount: count,
      avgAmount: total / count,
    }))
    .sort((a, b) => b.totalAmount - a.totalAmount);
}

export function getFlaggedAllocations(): MPLADSAllocation[] {
  return localAllocations.filter((a) => a.dataQualityFlags.length > 0);
}

export async function fetchAllocationsFromDB(): Promise<MPLADSAllocation[]> {
  const { data, error } = await supabase
    .from('mplads_allocations')
    .select('*')
    .order('serial_number', { ascending: true });

  if (error) {
    console.warn('Supabase fetch failed, falling back to local data:', error.message);
    return localAllocations;
  }
  if (!data || data.length === 0) {
    return localAllocations;
  }
  return data.map((row) => ({
    id: row.id,
    serialNumber: row.serial_number,
    state: row.state,
    mpName: row.mp_name,
    constituency: row.constituency,
    allocatedAmount: Number(row.allocated_amount),
    sourceName: row.source_name,
    sourceUrl: row.source_url,
    sourceRetrievedAt: row.source_retrieved_at,
    sourceRow: row.source_row,
    dataQualityFlags: row.data_quality_flags || [],
  }));
}

export function getTotalAllocatedAmount(): number {
  return localAllocations.reduce((sum, a) => sum + a.allocatedAmount, 0);
}

export function getUniqueMPCount(): number {
  return new Set(localAllocations.map((a) => a.mpName)).size;
}

export function getUniqueStateCount(): number {
  return new Set(localAllocations.map((a) => a.state)).size;
}
